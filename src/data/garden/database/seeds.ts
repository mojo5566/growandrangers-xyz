export function getSeedById(id: string): Seed | undefined {
  return seeds.find((s) => s.id === id);
}

export function getSeedByName(name: string): Seed | undefined {
  const lower = name.toLowerCase();
  return seeds.find(
    (s) =>
      s.name.toLowerCase() === lower ||
      s.aliases.some((a) => a.toLowerCase() === lower)
  );
}

export function getSeedsByTier(tier: Seed["tier"]): Seed[] {
  return seeds.filter((s) => s.tier === tier);
}

export function getSeedsByRarity(rarity: Seed["rarity"]): Seed[] {
  return seeds.filter((s) => s.rarity === rarity);
}

export function getSeedsByCurrency(currency: Seed["currency"]): Seed[] {
  return seeds.filter((s) => s.currency === currency);
}

export function getSeedsBySeason(season: Seed["season"]): Seed[] {
  return seeds.filter((s) => s.season === season || s.season === "All");
}
